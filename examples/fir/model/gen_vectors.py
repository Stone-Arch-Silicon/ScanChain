#!/usr/bin/env python3
"""Golden FIR model + vector/coeff-header generator. y[n]=sum h[k]x[n-k], zero history, exact integer math."""
import random, pathlib, sys
sys.path.insert(0, str(pathlib.Path(__file__).parent))
from coeffs import H
ROOT = pathlib.Path(__file__).parent.parent
N = 2048

def fir(x, h):
    return [sum(h[k] * (x[n-k] if n-k >= 0 else 0) for k in range(len(h))) for n in range(len(x))]

def stim(n=N, seed=1):
    r = random.Random(seed)
    x = [0]*4 + [32767] + [0]*11            # impulse (should echo taps)
    x += [-32768]*16 + [32767]*16           # full-scale steps (overflow/sign check)
    x += [r.randint(-32768, 32767) for _ in range(n - len(x))]
    return x

def hx(v, bits):  return f"{v & ((1 << bits) - 1):0{(bits+3)//4}x}"

if __name__ == "__main__":
    x = stim(); y = fir(x, H)
    (ROOT/"vectors").mkdir(exist_ok=True)
    (ROOT/"vectors/x.hex").write_text("\n".join(hx(v,16) for v in x) + "\n")
    (ROOT/"vectors/y_exp.hex").write_text("\n".join(hx(v,35) for v in y) + "\n")
    lines = ["// GENERATED by model/gen_vectors.py from model/coeffs.py -- do not edit"]
    for k, v in enumerate(H):
        lines.append(f"localparam signed [15:0] H{k} = {'-' if v<0 else ''}16'sd{abs(v)};")
    (ROOT/"rtl/fir_coeffs.vh").write_text("\n".join(lines) + "\n")
    print(f"wrote {len(x)} vectors; max|y|={max(map(abs,y))} (35b limit {2**34})")
